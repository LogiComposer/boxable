package be.quodlibet.boxable;

/**
 * Enumeration for font style variants.
 * 
 * @author Boxable
 */
public enum FontStyle {
    /**
     * Regular/normal font style
     */
    REGULAR,
    
    /**
     * Bold font style
     */
    BOLD,
    
    /**
     * Italic font style
     */
    ITALIC,
    
    /**
     * Bold and italic combined font style
     */
    BOLD_ITALIC
}